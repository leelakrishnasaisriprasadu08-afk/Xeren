"""Domain models and receipts for Xeren Sovereign Knowledge DB subsystem."""

import time
import uuid
from typing import Any, Dict, List, Optional, Set
from pydantic import BaseModel, Field

from xeren.rag.document import DocumentChunk
from xeren.rag.knowledge_db.schema.enums import (
    ClaimType,
    HealthState,
    KnowledgeLifecycleState,
    KnowledgeRelationshipType,
    TelemetryPrivacyPolicy,
)


class SourceRecord(BaseModel):
    """Origin entity of ingested content (file path, URL, git commit)."""

    source_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    source_type: str = Field(..., description="file, git_repo, web, api, manual")
    source_uri: str = Field(..., description="Unique uniform resource identifier")
    created_at: float = Field(default_factory=time.time)
    updated_at: float = Field(default_factory=time.time)


class DocumentRecord(BaseModel):
    """The authoritative document entity in the Source Layer."""

    document_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    source_id: str = Field(..., description="Foreign key reference to source_id")
    title: Optional[str] = Field(default=None)
    content_hash: str = Field(..., description="SHA-256 content checksum")
    current_version: int = Field(default=1, ge=1)
    lifecycle_state: KnowledgeLifecycleState = Field(default=KnowledgeLifecycleState.INGESTED)
    owner: str = Field(default="sovereign_user")
    workspace_id: str = Field(default="default")
    access_level: str = Field(default="LIBERAL")  # LIBERAL, SENSITIVE, RESTRICTED
    sensitivity_tier: str = Field(default="INTERNAL")
    retention_policy: str = Field(default="FOREVER")
    superseded_by_doc_id: Optional[str] = Field(default=None)
    created_at: float = Field(default_factory=time.time)
    updated_at: float = Field(default_factory=time.time)


class DocumentVersionRecord(BaseModel):
    """Immutable version snapshot tracking document evolution."""

    version_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    document_id: str = Field(...)
    version_number: int = Field(..., ge=1)
    content_path: str = Field(...)
    content_hash: str = Field(...)
    change_summary: Optional[str] = Field(default=None)
    created_at: float = Field(default_factory=time.time)


class ChunkRecord(BaseModel):
    """The fundamental retrieval atom in the Knowledge Layer."""

    chunk_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    document_id: str = Field(...)
    version_number: int = Field(default=1, ge=1)
    chunk_index: int = Field(..., ge=0)
    content: str = Field(...)
    token_count: int = Field(..., ge=0)
    section_title: Optional[str] = Field(default=None)
    page_number: Optional[int] = Field(default=None)
    parent_chunk_id: Optional[str] = Field(default=None)
    content_hash: str = Field(...)
    created_at: float = Field(default_factory=time.time)


class KnowledgeRelationshipRecord(BaseModel):
    """Semantic graph edge linking two chunks in the Knowledge Layer."""

    relationship_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    source_chunk_id: str = Field(...)
    relationship_type: KnowledgeRelationshipType = Field(...)
    target_chunk_id: str = Field(...)
    confidence: float = Field(default=1.0, ge=0.0, le=1.0)
    evidence_reference: Optional[str] = Field(default=None)
    model_id: str = Field(default="xeren_ingest")
    created_by: str = Field(default="system")
    status: str = Field(default="ACTIVE")
    created_at: float = Field(default_factory=time.time)


class ClaimRecord(BaseModel):
    """An asserted statement or rule extracted or generated by Xeren."""

    claim_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    statement: str = Field(...)
    claim_type: ClaimType = Field(default=ClaimType.FACT)
    confidence: float = Field(default=1.0, ge=0.0, le=1.0)
    created_at: float = Field(default_factory=time.time)


class ClaimEvidenceRecord(BaseModel):
    """Associates a chunk as grounded evidence supporting or refuting a claim."""

    evidence_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    claim_id: str = Field(...)
    chunk_id: str = Field(...)
    relevance_score: float = Field(default=1.0, ge=0.0, le=1.0)
    verification_status: str = Field(default="UNVERIFIED")  # VERIFIED, REFUTED, UNVERIFIED
    verified_by_model: Optional[str] = Field(default=None)
    created_at: float = Field(default_factory=time.time)


class ProvenanceRecord(BaseModel):
    """Immutable audit trail linking claim/chunk back to origin source."""

    provenance_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    claim_id: Optional[str] = Field(default=None)
    chunk_id: str = Field(...)
    document_id: str = Field(...)
    source_uri: str = Field(...)
    document_version: int = Field(...)
    page_number: Optional[int] = Field(default=None)
    recorded_at: float = Field(default_factory=time.time)


class RetrievalEventRecord(BaseModel):
    """Audit log entry capturing a retrieval event for learning and monitoring."""

    event_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    query_id: str = Field(...)
    query_hash: str = Field(..., description="SHA-256 of normalized query text")
    query_text: Optional[str] = Field(default=None, description="Only populated when permitted by privacy policy")
    chunk_id: str = Field(...)
    retrieval_method: str = Field(...)  # 'dense_vector', 'bm25_lexical', 'graph_relation', 'hybrid_rrf'
    rank_position: int = Field(..., ge=1)
    score: float = Field(...)
    user_or_task_id: Optional[str] = Field(default=None)
    workspace_id: str = Field(default="default")
    timestamp: float = Field(default_factory=time.time)


class EmbeddingRecord(BaseModel):
    """Decoupled vector metadata in SQLite (actual vectors live in pluggable index)."""

    embedding_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    chunk_id: str = Field(...)
    model_id: str = Field(...)
    dimension: int = Field(..., ge=1)
    index_id: str = Field(...)
    vector_blob: Optional[bytes] = Field(default=None, description="Optional IEEE 754 binary recovery backup")
    version: int = Field(default=1, ge=1)
    created_at: float = Field(default_factory=time.time)


# ---------------------------------------------------------------------------
# High-Level API Receipts and Results
# ---------------------------------------------------------------------------

class IngestionReceipt(BaseModel):
    """Confirmation receipt returned after document ingestion."""

    document_id: str
    source_id: str
    source_uri: str
    version: int
    chunks_created: int
    embeddings_created: int
    content_hash: str
    lifecycle_state: KnowledgeLifecycleState
    elapsed_ms: float


class ClaimReceipt(BaseModel):
    """Confirmation receipt returned after registering an assertion with evidence."""

    claim_id: str
    statement: str
    evidence_count: int
    provenance_ids: List[str]


class KnowledgeRetrievalItem(BaseModel):
    """Single retrieved chunk with score, relationships, and full provenance."""

    chunk: DocumentChunk
    score: float
    retrieval_method: str
    relationships: List[KnowledgeRelationshipRecord] = Field(default_factory=list)
    provenance: Optional[ProvenanceRecord] = None


class KnowledgeRetrievalResult(BaseModel):
    """Consolidated retrieval result produced by the Knowledge DB."""

    query_id: str
    query_hash: str
    items: List[KnowledgeRetrievalItem] = Field(default_factory=list)
    total_candidates_found: int = 0
    latency_ms: float = 0.0
    workspace_id: str = "default"


class BackupManifest(BaseModel):
    """Manifest describing a verified transactional backup snapshot."""

    manifest_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    created_at: float = Field(default_factory=time.time)
    checkpoint_sequence: int = Field(default=1)
    metadata_checksum_sha256: str
    indexes_checksum_sha256: str
    documents_count: int
    chunks_count: int
    embeddings_count: int
    manifest_version: str = "1.0.0"
    is_verified: bool = False


class KnowledgeDBHealth(BaseModel):
    """System health report."""

    primary_state: HealthState
    backup_state: HealthState
    primary_db_size_bytes: int = 0
    total_documents: int = 0
    total_chunks: int = 0
    total_relationships: int = 0
    total_claims: int = 0
    last_backup_timestamp: Optional[float] = None
    diagnostics: List[str] = Field(default_factory=list)
