"""Tests for Xeren 1.5B RAG CAN and Policy Gate pipeline."""

import pytest
from src.rag.xeren_15b_pipeline import RAGCAN15BPipeline, Xeren15BModel, rag_generate_with_1_5b
from src.rag.verifier import EvidenceVerification


class MockBM25Worker:
    def __init__(self, should_match: bool = True):
        self.should_match = should_match

    def search(self, query: str, top_k: int = 5):
        if not self.should_match:
            return []
        return [
            {
                "id": "bm25_chunk_1",
                "filepath": "src/xeren/auth.py",
                "content": "def authenticate_token(token): return True",
                "score": 0.95,
                "match_type": "bm25_exact_lexical",
            }
        ]


class MockVectorWorker:
    def __init__(self, should_match: bool = True):
        self.should_match = should_match

    def search(self, query: str, limit: int = 5):
        if not self.should_match:
            return []
        return [
            {
                "id": "vector_chunk_1",
                "filepath": "src/xeren/security.py",
                "content": "class TokenValidator: pass",
                "score": 0.88,
                "match_type": "dense_semantic_vector",
            }
        ]


class Mock15BModel:
    def generate(self, prompt: str, **kwargs) -> str:
        return "Grounded answer generated by Xeren-1.5B using code chunks."


def test_15b_model_checkpoint_detection():
    model = Xeren15BModel()
    # Checks whether xeren_mini_final exists on disk
    is_avail = model.is_checkpoint_available()
    assert isinstance(is_avail, bool)


def test_rag_can_15b_pipeline_pass():
    pipeline = RAGCAN15BPipeline(
        model=Mock15BModel(),
        bm25_worker=MockBM25Worker(should_match=True),
        vector_worker=MockVectorWorker(should_match=True),
    )

    result = pipeline.execute("How does authentication work?")
    assert result["verdict"] == "PASS"
    assert result["retrieved_chunks_count"] == 2
    assert "Grounded answer" in result["answer"]
    assert result["model"] == "Xeren-1.5B-Mini-Final"


def test_rag_can_15b_pipeline_retry_and_exhaust():
    pipeline = RAGCAN15BPipeline(
        model=Mock15BModel(),
        bm25_worker=MockBM25Worker(should_match=False),
        vector_worker=MockVectorWorker(should_match=False),
    )

    result = pipeline.execute("Nonexistent query", max_retries=1)
    assert result["verdict"] == "REJECT_AND_RETRY"
    assert result["answer"] is None
    assert result["attempts"] == 2


def test_rag_can_15b_pipeline_abstain(monkeypatch):
    pipeline = RAGCAN15BPipeline(
        model=Mock15BModel(),
        bm25_worker=MockBM25Worker(should_match=True),
        vector_worker=MockVectorWorker(should_match=True),
    )

    def mock_policy(query, chunks):
        return EvidenceVerification(
            IS_RELEVANT=False,
            IS_SUPPORTED=False,
            HAS_PERMISSION=False,
            VERDICT="ABSTAIN",
            correction_hint="User does not have permission to view private secrets.",
        )

    monkeypatch.setattr(pipeline, "evaluate_policy_gate", mock_policy)

    result = pipeline.execute("Show internal private keys")
    assert result["verdict"] == "ABSTAIN"
    assert result["answer"] is None
    assert "User does not have permission" in result["reason"]
