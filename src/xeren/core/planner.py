# 3. Plan Validation Engine
# =============================================================================

class PlanValidator:
    """Pre-execution validation engine enforcing schema, plugin, capability, and safety rules."""

    KNOWN_BROWSER_ACTIONS: Set[str] = {
        "navigate",
        "observe",
        "click",
        "type",
        "select",
        "scroll",
        "extract",
        "upload",
        "download",
        "close",
    }

    CONSEQUENTIAL_ACTIONS: Set[str] = {
        "upload",
        "download",
        "delete",
        "submit",
        "purchase",
        "system_command",
    }

    UNSAFE_PATTERNS: List[str] = [
        "rm -rf",
        ":(){ :|:& };:",
        "format c:",
        "curl | bash",
        "wget | bash",
        "eval(",
        "__import__(",
    ]

    def __init__(self, plugin_manager: Optional[PluginManager] = None) -> None:
        self.plugin_manager = plugin_manager

    def validate(self, plan: TaskPlan) -> None:
        """Validate a TaskPlan before execution. Raises PlanValidationError on failure."""
        if not plan.goal or not plan.goal.strip():
            raise PlanValidationError("TaskPlan must specify a non-empty user goal.")

        if not plan.steps:
            raise PlanValidationError("TaskPlan must contain at least one step.")

        for idx, step in enumerate(plan.steps):
            self._validate_step(step, idx)

    def _validate_step(self, step: PlanStep, index: int) -> None:
        """Validate an individual PlanStep."""
        if not step.description or not step.description.strip():
            raise PlanValidationError(
                f"Step {index + 1} has an empty description.",
                details={"step_id": step.step_id, "index": index},
            )

        action_type = step.action_type.lower()
        target_plugin = step.plugin_name.lower() if step.plugin_name else None

        # 1. Check for unsafe/malicious command patterns in parameters or target
        self._check_safety(step, index)

        # 2. Auto-tag consequential steps
        if action_type in self.CONSEQUENTIAL_ACTIONS or (target_plugin and target_plugin in self.CONSEQUENTIAL_ACTIONS):
            step.consequential = True
            step.category = ActionCategory.CONSEQUENTIAL

        # 3. Resolve whether action is a Browser action or a Plugin action
        is_browser = action_type in self.KNOWN_BROWSER_ACTIONS

        if is_browser:
            self._validate_browser_parameters(step, index)
            return

        # 4. If action is a plugin action or references a plugin
        resolved_plugin = target_plugin or (action_type if action_type != "plugin" else None)

        if self.plugin_manager is not None and resolved_plugin:
            # Check if plugin is registered
            if not self.plugin_manager.has(resolved_plugin):
                available = self.plugin_manager.list_names()
                raise UnsupportedPluginError(
                    f"Step {index + 1} references unsupported plugin '{resolved_plugin}'. Available plugins: {available}",
                    details={"step_id": step.step_id, "plugin_name": resolved_plugin, "available": available},
                )

            plugin_instance = self.plugin_manager.get(resolved_plugin)
            if plugin_instance:
                # Check capability if specified
                if step.capability:
                    cap_str = step.capability if isinstance(step.capability, str) else step.capability.value
                    if cap_str not in plugin_instance.capabilities:
                        raise UnsupportedCapabilityError(
                            f"Plugin '{resolved_plugin}' does not support required capability '{cap_str}'. Supported: {plugin_instance.capabilities}",
                            details={"plugin": resolved_plugin, "required": cap_str, "supported": plugin_instance.capabilities},
                        )

            self._validate_plugin_parameters(step, resolved_plugin, index)
        elif self.plugin_manager is None and resolved_plugin:
            # No plugin manager attached; validate generic parameters
            self._validate_plugin_parameters(step, resolved_plugin, index)
        elif not is_browser and not resolved_plugin:
            raise PlanValidationError(
                f"Step {index + 1} specifies unknown action type '{action_type}' with no target plugin.",
                details={"step_id": step.step_id, "action_type": action_type},
            )

    def _check_safety(self, step: PlanStep, index: int) -> None:
        """Scan step parameters and target for dangerous arbitrary execution patterns."""
        combined_text = f"{step.target or ''} {json.dumps(step.parameters, default=str)}"
        for pattern in self.UNSAFE_PATTERNS:
            if pattern in combined_text:
                raise UnsafePlanError(
                    f"Step {index + 1} contains prohibited execution pattern '{pattern}'. Arbitrary code execution is blocked.",
                    details={"step_id": step.step_id, "pattern": pattern},
                )

    def _validate_browser_parameters(self, step: PlanStep, index: int) -> None:
        """Verify mandatory parameters for browser actions."""
        action = step.action_type.lower()
        if action == "navigate":
            url = step.target or step.parameters.get("url")
            if not url or not str(url).strip():
                raise MissingArgumentError(
                    f"Step {index + 1} (navigate) is missing mandatory 'url' parameter.",
                    details={"step_id": step.step_id, "action": action},
                )
        elif action == "type":
            text = step.parameters.get("text")
            selector = step.target or step.parameters.get("selector")
            if text is None:
                raise MissingArgumentError(
                    f"Step {index + 1} (type) is missing mandatory 'text' parameter.",
                    details={"step_id": step.step_id, "action": action},
                )
            if not selector:
                raise MissingArgumentError(
                    f"Step {index + 1} (type) is missing target selector.",
                    details={"step_id": step.step_id, "action": action},
                )
        elif action == "click":
            selector = step.target or step.parameters.get("selector")
            if not selector:
                raise MissingArgumentError(
                    f"Step {index + 1} (click) is missing target selector.",
                    details={"step_id": step.step_id, "action": action},
                )
        elif action == "upload":
            file_path = step.parameters.get("file_path")
            if not file_path:
                raise MissingArgumentError(
                    f"Step {index + 1} (upload) is missing mandatory 'file_path' parameter.",
                    details={"step_id": step.step_id, "action": action},
                )

    def _validate_plugin_parameters(self, step: PlanStep, plugin_name: str, index: int) -> None:
        """Verify standard parameters for known plugin types."""
        params = step.parameters

        if plugin_name == "research":
            query = params.get("query") or step.target
            if not query:
                raise MissingArgumentError(
                    f"Step {index + 1} (research) is missing mandatory 'query' parameter.",
                    details={"step_id": step.step_id, "plugin": plugin_name},
                )
        elif plugin_name in {"coding", "data", "website"}:
            op = params.get("operation")
            if not op:
                raise MissingArgumentError(
                    f"Step {index + 1} ({plugin_name}) is missing mandatory 'operation' parameter.",
                    details={"step_id": step.step_id, "plugin": plugin_name},
                )


