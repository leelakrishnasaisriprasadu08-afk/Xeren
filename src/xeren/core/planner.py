# 2. Planning Exceptions Hierarchy
# =============================================================================

class PlanningError(Exception):
    """Base exception for all core planning failures."""

    def __init__(self, message: str, details: Optional[Dict[str, Any]] = None) -> None:
        super().__init__(message)
        self.message = message
        self.details = details or {}


class PlanValidationError(PlanningError):
    """Raised when a generated or input plan fails schema or safety validation."""
    pass


class UnsupportedPluginError(PlanValidationError):
    """Raised when a plan references a plugin that is not registered."""
    pass


class UnsupportedCapabilityError(PlanValidationError):
    """Raised when a plan requests a capability not supported by available plugins."""
    pass


class MissingArgumentError(PlanValidationError):
    """Raised when a plan step is missing mandatory parameters."""
    pass


class UnsafePlanError(PlanValidationError):
    """Raised when a plan contains prohibited or unsafe execution requests."""
    pass


class ModelInferenceError(PlanningError):
    """Raised when the planning model fails to produce an inference response."""
    pass


class PlannerTimeoutError(PlanningError):
    """Raised when model plan generation exceeds allowable time limit after retries."""
    pass


