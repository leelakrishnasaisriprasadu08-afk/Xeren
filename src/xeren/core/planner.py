class BaseCoreModelAdapter(ABC):
    """Abstract interface decoupling raw model loading/inference from planner orchestration."""

    @abstractmethod
    def infer_plan(self, plan_context: PlanContext) -> Dict[str, Any]:
        """Synchronously produce raw structured plan dictionary from model."""
        pass

    @abstractmethod
    async def ainfer_plan(self, plan_context: PlanContext) -> Dict[str, Any]:
        """Asynchronously produce raw structured plan dictionary from model."""
        pass


class LLMCoreModelAdapter(BaseCoreModelAdapter):
    """Adapter wrapping any BaseLLM provider for structured TaskPlan inference."""

    def __init__(
        self,
        llm: BaseLLM,
        timeout_seconds: float = 30.0,
        enable_fallback: bool = True,
    ) -> None:
        self.llm = llm
        self.timeout_seconds = timeout_seconds
        self.enable_fallback = enable_fallback
        self._fallback_adapter = DeterministicCoreModelAdapter()

    def _build_prompt(self, plan_context: PlanContext) -> List[ChatMessage]:
        plugins_desc = ", ".join(plan_context.available_plugins) if plan_context.available_plugins else "browser"
        caps_desc = ", ".join(plan_context.available_capabilities) if plan_context.available_capabilities else "standard"
        system_msg = (
            "You are the Xeren Core Planner. Decompose the user goal into a strict JSON TaskPlan.\n"
            f"Available plugins: {plugins_desc}\n"
            f"Available capabilities: {caps_desc}\n"
            "Respond strictly with valid JSON conforming to the TaskPlan schema without commentary."
        )
        user_msg = f"Goal: {plan_context.goal}\nContext: {json.dumps(plan_context.task_context, default=str)}"
        return [ChatMessage.system(system_msg), ChatMessage.user(user_msg)]

    def infer_plan(self, plan_context: PlanContext) -> Dict[str, Any]:
        messages = self._build_prompt(plan_context)
        try:
            res = self.llm.generate_structured(messages, TaskPlan)
            return res.model_dump()
        except (ValidationError, OutputParsingError, json.JSONDecodeError) as err:
            if self.enable_fallback:
                logger.warning("Model produced malformed JSON for TaskPlan. Engaging safe recovery fallback: %s", err)
                return self._fallback_adapter.infer_plan(plan_context)
            raise PlanValidationError(f"Model output failed schema validation: {err}", details={"errors": str(err)}) from err
        except Exception as err:
            if self.enable_fallback:
                logger.warning("Model inference failed. Engaging safe recovery fallback: %s", err)
                return self._fallback_adapter.infer_plan(plan_context)
            raise ModelInferenceError(f"Model inference failed: {err}", details={"raw_error": str(err)}) from err

    async def ainfer_plan(self, plan_context: PlanContext) -> Dict[str, Any]:
        messages = self._build_prompt(plan_context)
        try:
            res = await self.llm.agenerate_structured(messages, TaskPlan)
            return res.model_dump()
        except (ValidationError, OutputParsingError, json.JSONDecodeError) as err:
            if self.enable_fallback:
                logger.warning("Model produced malformed JSON for TaskPlan. Engaging safe recovery fallback: %s", err)
                return await self._fallback_adapter.ainfer_plan(plan_context)
            raise PlanValidationError(f"Model output failed schema validation: {err}", details={"errors": str(err)}) from err
        except Exception as err:
            if self.enable_fallback:
                logger.warning("Model inference failed. Engaging safe recovery fallback: %s", err)
                return await self._fallback_adapter.ainfer_plan(plan_context)
            raise ModelInferenceError(f"Model inference failed: {err}", details={"raw_error": str(err)}) from err


