# 5. Stable CorePlanner Interface and Adapter
# =============================================================================

class BaseCorePlanner(ABC):
    """Stable interface through which Xeren Core provides plans to the Autonomous Agent."""

    @abstractmethod
    def create_task_plan(self, goal: str, context: Optional[Dict[str, Any]] = None) -> TaskPlan:
        """Synchronously create and validate a structured TaskPlan from user goal and context."""
        pass

    @abstractmethod
    async def acreate_task_plan(self, goal: str, context: Optional[Dict[str, Any]] = None) -> TaskPlan:
        """Asynchronously create and validate a structured TaskPlan from user goal and context."""
        pass


class CorePlannerAdapter(Planner, BaseCorePlanner):
    """Production planner adapter connecting Xeren Core models to AgentController.

    Features:
    - Decoupled model inference via BaseCoreModelAdapter.
    - Pre-execution validation via PlanValidator.
    - Bounded retries and timeout protection.
    - Duck-typed compatibility with AgentController (create_plan, next_action, replan).
    """

    def __init__(
        self,
        model_adapter: Optional[BaseCoreModelAdapter] = None,
        llm: Optional[BaseLLM] = None,
        plugin_manager: Optional[PluginManager] = None,
        max_retries: int = 2,
        timeout_seconds: float = 10.0,
        enable_fallback: bool = True,
    ) -> None:
        super().__init__(llm=llm)
        self.plugin_manager = plugin_manager
        self.validator = PlanValidator(plugin_manager=plugin_manager)
        self.max_retries = max_retries
        self.timeout_seconds = timeout_seconds
        self.enable_fallback = enable_fallback

        # Configure model adapter
        if model_adapter is not None:
            self.model_adapter = model_adapter
        elif llm is not None:
            self.model_adapter = LLMCoreModelAdapter(
                llm=llm, timeout_seconds=timeout_seconds, enable_fallback=enable_fallback
            )
        else:
            self.model_adapter = DeterministicCoreModelAdapter()

        # Cache active TaskPlans indexed by session or task
        self._active_plans: Dict[str, TaskPlan] = {}

    def _build_context(self, goal: str, context: Optional[Dict[str, Any]] = None) -> PlanContext:
        ctx = context or {}
        available_plugins = self.plugin_manager.list_names() if self.plugin_manager else []
        available_caps: List[str] = []
        if self.plugin_manager:
            for p in self.plugin_manager.list_plugins():
                available_caps.extend(p.capabilities)

        return PlanContext(
            goal=goal,
            task_context=ctx,
            available_plugins=available_plugins,
            available_capabilities=list(set(available_caps)),
            constraints=ctx.get("constraints", []),
            metadata=ctx.get("metadata", {}),
        )

    def create_task_plan(self, goal: str, context: Optional[Dict[str, Any]] = None) -> TaskPlan:
        """Synchronously create and validate TaskPlan with bounded retries."""
        plan_context = self._build_context(goal, context)
        last_error: Optional[Exception] = None

        for attempt in range(self.max_retries + 1):
            try:
                raw_plan = self.model_adapter.infer_plan(plan_context)
                if not isinstance(raw_plan, dict):
                    raise PlanValidationError("Model failed to output a structured dictionary plan.")

                task_plan = TaskPlan.model_validate(raw_plan)
                self.validator.validate(task_plan)
                return task_plan

            except (UnsupportedPluginError, UnsupportedCapabilityError, MissingArgumentError, UnsafePlanError):
                # Don't retry structural or safety rejection errors
                raise
            except (PlanValidationError, ModelInferenceError, Exception) as err:
                last_error = err
                logger.warning("Plan generation attempt %d failed: %s", attempt + 1, err)
                if attempt == self.max_retries:
                    break

        if isinstance(last_error, PlanningError):
            raise last_error
        raise ModelInferenceError(f"Planning failed after {self.max_retries + 1} attempts: {last_error}")

    async def acreate_task_plan(self, goal: str, context: Optional[Dict[str, Any]] = None) -> TaskPlan:
        """Asynchronously create and validate TaskPlan with timeout and bounded retries."""
        plan_context = self._build_context(goal, context)
        last_error: Optional[Exception] = None

        for attempt in range(self.max_retries + 1):
            try:
                coro = self.model_adapter.ainfer_plan(plan_context)
                raw_plan = await asyncio.wait_for(coro, timeout=self.timeout_seconds)

                if not isinstance(raw_plan, dict):
                    raise PlanValidationError("Model failed to output a structured dictionary plan.")

                task_plan = TaskPlan.model_validate(raw_plan)
                self.validator.validate(task_plan)
                return task_plan

            except asyncio.TimeoutError as err:
                last_error = err
                logger.warning("Plan generation attempt %d timed out after %.2fs", attempt + 1, self.timeout_seconds)
                if attempt == self.max_retries:
                    raise PlannerTimeoutError(
                        f"Model plan generation timed out after {self.max_retries + 1} attempts.",
                        details={"timeout_seconds": self.timeout_seconds, "attempts": self.max_retries + 1},
                    ) from err
            except (UnsupportedPluginError, UnsupportedCapabilityError, MissingArgumentError, UnsafePlanError):
                # Don't retry deterministic safety or capability errors
                raise
            except (PlanValidationError, ModelInferenceError, Exception) as err:
                last_error = err
                logger.warning("Plan generation attempt %d failed: %s", attempt + 1, err)
                if attempt == self.max_retries:
                    break

        if isinstance(last_error, PlanningError):
            raise last_error
        raise ModelInferenceError(f"Planning failed after {self.max_retries + 1} attempts: {last_error}")

    # -------------------------------------------------------------------------
    # Duck-typed methods for seamless AgentController integration
    # -------------------------------------------------------------------------

    def create_plan(self, task: str, context: Optional[Dict[str, Any]] = None) -> List[str]:
        """Produce step description strings for AgentController, caching the TaskPlan."""
        if context and "task_plan" in context and isinstance(context["task_plan"], TaskPlan):
            task_plan = context["task_plan"]
        else:
            task_plan = self.create_task_plan(task, context)
        key = context.get("session_id", task) if context else task
        self._active_plans[key] = task_plan
        return [step.description for step in task_plan.steps]

    def next_action(self, state: AgentState) -> Optional[AgentAction]:
        """Convert the next PlanStep in the active TaskPlan into an executable AgentAction."""
        key = state.session_id or state.task
        task_plan = self._active_plans.get(key)

        if task_plan is None:
            # Generate TaskPlan if not already present
            task_plan = self.create_task_plan(state.task, state.memory)
            self._active_plans[key] = task_plan
            state.plan = [step.description for step in task_plan.steps]

        state.task_plan = task_plan

        if state.step_count >= len(task_plan.steps):
            return None  # All steps executed

        current_step_model = task_plan.steps[state.step_count]
        state.current_step = current_step_model.description

        # Map PlanStep into AgentAction
        action = AgentAction(
            action_id=current_step_model.step_id,
            action_type=current_step_model.action_type,
            target=current_step_model.target,
            parameters=dict(current_step_model.parameters),
            consequential=current_step_model.consequential,
            category=current_step_model.category,
            description=current_step_model.description,
        )

        # Attach plugin_name if defined
        if current_step_model.plugin_name:
            action.parameters["plugin_name"] = current_step_model.plugin_name
        if current_step_model.capability:
            action.parameters["capability"] = current_step_model.capability

        return action

    def replan(self, state: AgentState, failure_reason: str) -> List[str]:
        """Adapt active plan in response to a failed step."""
        logger.info("CorePlannerAdapter replanning due to: %s", failure_reason)
        key = getattr(state, "session_id", getattr(state, "task_id", getattr(state, "task", getattr(state, "goal", "default"))))
        active_plan = self._active_plans.get(key)

        revised_steps: List[PlanStep] = []
        if active_plan:
            # Preserve completed steps
            for i in range(min(state.step_count, len(active_plan.steps))):
                revised_steps.append(active_plan.steps[i])

        # Inject diagnostic and recovery step
        diag_step = PlanStep(
            step_id=str(uuid.uuid4()),
            description=f"Inspect state after failure: {failure_reason}",
            action_type="observe",
            category=ActionCategory.READ_ONLY,
        )
        revised_steps.append(diag_step)

        # Update cached plan
        if active_plan:
            active_plan.steps = revised_steps
            state.plan = [s.description for s in revised_steps]
        else:
            state.plan.append(diag_step.description)

        return state.plan

    async def areplan(
        self,
        failed_step: Optional[PlanStep] = None,
        error_message: str = "",
        context: Optional[Dict[str, Any]] = None,
        state: Optional[AgentState] = None,
        **kwargs: Any,
    ) -> Any:
        """Asynchronously replan, supporting both TaskPlan and AgentState formats."""
        if state is not None:
            return self.replan(state, error_message or kwargs.get("failure_reason", "Step execution failed"))

        # Replan from PlanStep
        err_msg = error_message or kwargs.get("failure_reason", "Step execution failed")
        step_id = failed_step.step_id if failed_step else str(uuid.uuid4())
        desc = f"Recover from failure in {failed_step.description if failed_step else 'step'}: {err_msg}"
        diag_step = PlanStep(
            step_id=str(uuid.uuid4()),
            description=desc,
            action_type="observe",
            category=ActionCategory.READ_ONLY,
        )
        return TaskPlan(
            plan_id=str(uuid.uuid4()),
            goal=f"Recover: {err_msg}",
            steps=[diag_step],
            context=context or {},
            metadata={"replan_source_step": step_id},
        )


