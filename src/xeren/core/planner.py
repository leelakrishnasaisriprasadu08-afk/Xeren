class PlanStep(BaseModel):
    """A single structured, validated step within a TaskPlan."""

    step_id: str = Field(default_factory=lambda: str(uuid.uuid4()), description="Unique step identifier")
    description: str = Field(..., description="Human-readable step objective")
    action_type: str = Field(default="plugin", description="Action type: browser action name, plugin name, or 'plugin'")
    plugin_name: Optional[str] = Field(default=None, description="Target plugin if this step dispatches to a plugin")
    capability: Optional[str] = Field(default=None, description="Required plugin or tool capability")
    target: Optional[str] = Field(default=None, description="Action target (e.g. URL, selector, file, or topic)")
    parameters: Dict[str, Any] = Field(default_factory=dict, description="Action input arguments and payloads")
    consequential: bool = Field(default=False, description="Whether action requires safety/permission checks")
    category: ActionCategory = Field(default=ActionCategory.INTERACTIVE, description="Risk classification")
    expected_outcome: Optional[str] = Field(default=None, description="Expected condition or outcome to verify")


class TaskPlan(BaseModel):
    """Validated structured plan generated by Xeren Core for autonomous execution."""

    plan_id: str = Field(default_factory=lambda: str(uuid.uuid4()), description="Plan identifier")
    goal: str = Field(..., description="Top-level user goal or prompt")
    steps: List[PlanStep] = Field(..., min_length=1, description="Ordered sequence of plan steps")
    context: Dict[str, Any] = Field(default_factory=dict, description="Task context and parameters")
    estimated_complexity: str = Field(default="standard", description="Estimated plan complexity level")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Diagnostic and planning metadata")

    def __contains__(self, key: Any) -> bool:
        return key in self.__dict__ or hasattr(self, str(key))

    def __getitem__(self, key: str) -> Any:
        if hasattr(self, key):
            return getattr(self, key)
        raise KeyError(key)


class PlanContext(BaseModel):
    """Structured context passed into Core Planner for plan generation."""

    goal: str = Field(..., description="User goal or task description")
    task_context: Dict[str, Any] = Field(default_factory=dict, description="Relevant task context and variables")
    available_plugins: List[str] = Field(default_factory=list, description="Names of available registered plugins")
    available_capabilities: List[str] = Field(default_factory=list, description="List of available plugin/tool capabilities")
    constraints: List[str] = Field(default_factory=list, description="Operational constraints")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Environment and session metadata")


